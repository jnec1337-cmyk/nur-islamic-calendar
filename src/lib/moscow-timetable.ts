const DAYS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

function minutes(clock: string): number {
  const [hh, mm] = clock.split(":").map(Number);
  return hh * 60 + mm;
}

function parseTable(source: string): string[][][] {
  const months: string[][][] = [];
  let current: string[][] | null = null;
  for (const line of source.trim().split("\n")) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (/^\d{1,2}$/.test(trimmed)) {
      current = [];
      months.push(current);
      continue;
    }
    const parts = trimmed.split(/\s+/);
    if (!current || parts.length !== 6) throw new Error(`bad row ${trimmed}`);
    current.push(parts);
  }
  return months;
}

const TABLE = parseTable(RAW);

export function moscowClocks(month: number, day: number): string[] {
  const rows = TABLE[month - 1] ?? TABLE[0]!;
  const index = Math.min(Math.max(day, 1), rows.length) - 1;
  return rows[index]!;
}

/** Wall clock of the Moscow table as an absolute instant. Moscow is UTC+3 all year. */
export function moscowInstant(year: number, month: number, day: number, clock: string): Date {
  const [hh, mm] = clock.split(":").map(Number);
  return new Date(Date.UTC(year, month - 1, day, hh - 3, mm, 0, 0));
}

export function moscowSlots(year: number, month: number, day: number): { id: (typeof ORDER)[number]; time: Date }[] {
  return moscowClocks(month, day).map((clock, index) => ({
    id: ORDER[index]!,
    time: moscowInstant(year, month, day, clock),
  }));
}

